#!/usr/bin/env node
/**
 * Generate the dependency part of THIRD_PARTY.md from the installed workspace.
 *
 * Sources: `pnpm licenses list --prod --json` (what the harness packages need at run
 * time) and `pnpm licenses list --json` (the whole installed tree: DeepSeek Harness,
 * which the container image installs as the host runtime, and the build tools).
 * Everything above the marker line of the existing file is hand-written and kept
 * as is; everything below it is replaced.
 *
 * Platform builds of a package (`<name>-<os>-<arch>`, e.g.
 * `@anthropic-ai/claude-agent-sdk-linux-x64`) are folded into the package name, so
 * the output does not depend on the machine that runs the generator.
 *
 * Usage: `pnpm third-party` (writes THIRD_PARTY.md) or `pnpm third-party --check`
 * (exit 1 when the file is out of date). Needs `pnpm install` first.
 */
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const TARGET = join(ROOT, 'THIRD_PARTY.md')
const MARKER = '<!-- generated-dependencies -->'
const COPYLEFT = /\b(A?GPL|LGPL|MPL|EUPL|CDDL|EPL|CC-BY-SA|OSL)\b/i
/** Proprietary dependency described in the hand-written part of the file. */
const PROPRIETARY = new Set(['@anthropic-ai/claude-agent-sdk'])
const PLATFORM = /-(darwin|linux|linuxmusl|win32|freebsd|android|wasm32)(-[a-z0-9]+)*$/

function licenses(prod) {
  const args = ['licenses', 'list', '--json', ...(prod ? ['--prod'] : [])]
  const raw = JSON.parse(execFileSync('pnpm', args, { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 << 20 }))
  const byName = new Map()
  for (const [license, packages] of Object.entries(raw)) {
    for (const p of packages) {
      const name = p.name.replace(PLATFORM, '')
      const entry = byName.get(name) ?? { name, versions: new Set(), license, paths: [] }
      for (const v of p.versions) entry.versions.add(v)
      // the package itself, not its platform build, carries the licence text
      if (name === p.name) entry.paths.unshift(...p.paths)
      else entry.paths.push(...p.paths)
      byName.set(name, entry)
    }
  }
  return [...byName.values()].sort((a, b) => a.name.localeCompare(b.name))
}

/** Distinct licence texts of a package and of its platform builds. */
function licenseTexts(paths) {
  const texts = []
  for (const dir of paths) {
    if (!existsSync(dir)) continue
    for (const file of readdirSync(dir).filter(f => /^(licen[cs]e|copying)/i.test(f) && statSync(join(dir, f)).isFile()).sort()) {
      const text = readFileSync(join(dir, file), 'utf8').replace(/\r\n/g, '\n').trim()
      if (!texts.includes(text)) texts.push(text)
    }
  }
  return texts
}

const line = p => `- ${p.name} ${[...p.versions].sort().join(', ')} — ${p.license}`
const dual = license => /\bOR\b/.test(license) && /\b(MIT|Apache-2\.0|BSD|ISC)\b/.test(license)

function render() {
  const prod = licenses(true)
  const all = licenses(false)
  const prodNames = new Set(prod.map(p => p.name))
  const dsh = all.filter(p => p.name.startsWith('@deepseek-ai/'))
  const out = [
    MARKER,
    '',
    '## Third-party npm dependencies',
    '',
    'Generated by `scripts/third-party.mjs` (`pnpm third-party`) from the installed',
    'workspace (`pnpm-lock.yaml`) with `pnpm licenses list`; do not edit below the',
    'marker by hand. Licence names come from package metadata. Platform builds of a',
    'package (`<name>-<os>-<arch>`) are listed once under the package name.',
    '',
    '### DeepSeek Harness',
    '',
    `The ${dsh.length} \`@deepseek-ai/*\` packages below are DeepSeek Harness and its own`,
    'libraries. This repository declares them as development dependencies; the',
    'container image built from `Dockerfile` installs them as the host runtime. They',
    'are used unmodified. The full licence texts follow the list.',
    '',
    ...dsh.map(line),
    '',
  ]
  const groups = new Map()
  for (const p of dsh) {
    const texts = licenseTexts(p.paths)
    for (const text of texts.length > 0 ? texts : [null]) {
      const key = text === null ? `none:${p.license}` : createHash('sha256').update(text).digest('hex')
      const group = groups.get(key) ?? { text, license: p.license, names: [] }
      group.names.push(p.name)
      groups.set(key, group)
    }
  }
  out.push('#### Licence texts', '')
  for (const g of [...groups.values()].sort((a, b) => b.names.length - a.names.length || a.names[0].localeCompare(b.names[0]))) {
    const who = g.names.length > 8 ? `${g.names.length} packages, among them ${g.names.slice(0, 3).map(n => `\`${n}\``).join(', ')}` : g.names.map(n => `\`${n}\``).join(', ')
    if (g.text === null) {
      out.push(`${who} — ${g.license}; the package ships no licence file.`, '')
      continue
    }
    out.push(`${who}:`, '', '```text', g.text, '```', '')
  }

  const runtime = prod.filter(p => !PROPRIETARY.has(p.name))
  const copyleft = runtime.filter(p => COPYLEFT.test(p.license) && !dual(p.license))
  const dualLicensed = runtime.filter(p => COPYLEFT.test(p.license) && dual(p.license))
  out.push(
    '### Run-time dependencies of the harness packages',
    '',
    'What `pnpm licenses list --prod` reports for the packages under `packages/`.',
    '`@anthropic-ai/claude-agent-sdk` is described in its own section above.',
    '',
  )
  if (copyleft.length > 0) out.push('#### Components under copyleft licences', '', ...copyleft.map(line), '')
  if (dualLicensed.length > 0) {
    out.push(
      '#### Dual-licensed components',
      '',
      'Used under the permissive option of the licence expression.',
      '',
      ...dualLicensed.map(line),
      '',
    )
  }
  out.push(
    '#### Other components',
    '',
    ...runtime.filter(p => !copyleft.includes(p) && !dualLicensed.includes(p)).map(line),
    '',
  )

  const rest = all.filter(p => !prodNames.has(p.name) && !p.name.startsWith('@deepseek-ai/') && COPYLEFT.test(p.license))
  out.push(
    '### Copyleft components outside the harness packages',
    '',
    'DeepSeek Harness packages, their dependencies and the build tools under a copyleft',
    'licence. None of them is part of the harness packages or modified here; the',
    'container image contains the ones DeepSeek Harness needs at run time.',
    '`pnpm licenses list` prints the complete tree.',
    '',
    ...dsh.filter(p => COPYLEFT.test(p.license)).map(line),
    ...rest.map(line),
    '',
  )
  return out.join('\n')
}

const existing = existsSync(TARGET) ? readFileSync(TARGET, 'utf8') : ''
const head = existing.includes(MARKER) ? existing.split(MARKER, 1)[0] : existing === '' ? '' : `${existing.trimEnd()}\n\n`
const next = `${head}${render()}`
if (process.argv.includes('--check')) {
  if (next !== existing) {
    console.error('THIRD_PARTY.md is out of date: run `pnpm third-party`')
    process.exit(1)
  }
  console.log('THIRD_PARTY.md is up to date')
} else {
  writeFileSync(TARGET, next)
  console.log(`THIRD_PARTY.md: ${next.split('\n').length} lines`)
}
